#!/usr/bin/env python3
"""Builds docs/index.json and docs/index.md: one row per docs page and per folder README (no network, no dependencies).

Each row: title, description, kind ("docs" or "readme"), path, and whether the file has its own metadata.
Metadata (`.agents/skills/readme-docs`):
- docs page: YAML front matter `title:` and `description:` (generated CEP pages: `method:` and `summary:`);
- folder README: an HTML comment `<!-- name: ... description: ... -->` at the top (GitHub hides it).
Generated CEP category pages (written by api/tests/cep_docs.rs) count as described.
A file without metadata falls back to its first heading and first paragraph and is marked `metadata: false`.

Run from the repository root:
  python docs/tools/build_index.py           writes both files
  python docs/tools/build_index.py --check   exit 1 when the files are out of date (used by check_docs.py)
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
INDEX_JSON = DOCS / "index.json"
INDEX_MD = DOCS / "index.md"
SKIP_DIRS = {"target", "node_modules", ".git", ".agent", "llama.cpp"}
SKIP_FILES = {INDEX_MD}

FRONT = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)
COMMENT = re.compile(r"\A\s*<!--(.*?)-->", re.S)
HEADING = re.compile(r"^#\s+(.+?)\s*$", re.M)


def field(block: str, name: str) -> str:
    match = re.search(rf"^\s*{name}:\s*(.+?)\s*$", block, re.M)
    return match.group(1).strip().strip("'\"") if match else ""


def plain(text: str) -> str:
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"<[^>]*>", "", text)
    text = re.sub(r"[`*_]", "", text)
    return re.sub(r"\s+", " ", text).strip()


def first_paragraph(body: str) -> str:
    body = re.sub(r"```.*?```|~~~.*?~~~", "", body, flags=re.S)
    for block in re.split(r"\r?\n\s*\r?\n", body):
        block = block.strip()
        if block and not re.match(r"^(#|\||>|[-*+]\s|\d+\.\s|<|---|!\[)", block):
            return plain(block)
    return ""


def short(text: str, limit: int = 200) -> str:
    return text if len(text) <= limit else text[:limit].rsplit(" ", 1)[0] + "..."


def read_row(path: Path, kind: str) -> dict:
    text = path.read_text(encoding="utf-8", errors="replace")
    rel = path.relative_to(ROOT).as_posix()
    title = description = ""
    body = text
    front = FRONT.match(text)
    comment = COMMENT.match(text)
    if front:
        block = front.group(1)
        title = field(block, "title") or field(block, "method")
        description = field(block, "description") or field(block, "summary")
        body = text[front.end():]
    elif comment and "description:" in comment.group(1):
        block = comment.group(1)
        title = field(block, "name")
        description = field(block, "description")
        body = text[comment.end():]
    generated = "Generated from the CEP registry" in text[:400]
    has_metadata = bool(title and description) or generated
    heading = HEADING.search(body)
    if not title:
        title = plain(heading.group(1)) if heading else rel
    if not description and generated:
        description = f"Generated list of the {plain(title)} CEP methods, from the Rust method registry."
    if not description:
        description = first_paragraph(body[heading.end():] if heading else body)
    return {
        "title": plain(title),
        "description": short(plain(description)),
        "kind": kind,
        "path": rel,
        "metadata": has_metadata,
    }


def tracked() -> list[Path]:
    """Files in git, so the index is the same on every machine and in CI (untracked run folders are left out)."""
    out = subprocess.run(["git", "ls-files", "-z", "--", "*.md"], cwd=ROOT, capture_output=True, check=True).stdout
    return [ROOT / name for name in out.decode("utf-8").split(chr(0)) if name]


def files() -> list[tuple[Path, str]]:
    found = []
    for path in sorted(tracked()):
        rel = path.relative_to(ROOT)
        if path in SKIP_FILES or set(rel.parts) & SKIP_DIRS or not path.is_file():
            continue
        if rel.parts[0] == "docs":
            found.append((path, "docs"))
        elif path.name.lower() == "readme.md" and len(rel.parts) > 1:
            found.append((path, "readme"))
    return sorted(found, key=lambda item: (item[1] != "docs", item[0].as_posix()))


def render(rows: list[dict]) -> tuple[str, str]:
    as_json = json.dumps(rows, indent=1, ensure_ascii=False) + "\n"
    missing = sum(1 for row in rows if not row["metadata"])
    lines = [
        "<!-- name: docs/index",
        "description: Every Engine docs page and folder README with its title and one-line description, generated by docs/tools/build_index.py. -->",
        "",
        "# All docs and code READMEs",
        "",
        "Generated by `python docs/tools/build_index.py`; do not edit by hand. The same list as JSON: [index.json](index.json).",
        f"{len(rows)} files; {missing} still without their own name and description (marked `*`, text taken from the file).",
        "",
    ]
    for kind, heading in (("docs", "Docs pages"), ("readme", "Code READMEs")):
        lines += [f"## {heading}", "", "| File | What it is |", "|---|---|"]
        for row in rows:
            if row["kind"] == kind:
                target = Path(row["path"]).relative_to("docs").as_posix() if kind == "docs" else "../" + row["path"]
                mark = "" if row["metadata"] else " *"
                text = row["description"].replace("|", "\\|") or row["title"].replace("|", "\\|")
                lines.append(f"| [{row['path']}]({target}){mark} | {text} |")
        lines.append("")
    return as_json, "\n".join(lines)


def build() -> tuple[str, str]:
    return render([read_row(path, kind) for path, kind in files()])


def main() -> int:
    as_json, as_md = build()
    if "--check" in sys.argv:
        stale = [p.relative_to(ROOT).as_posix() for p, want in ((INDEX_JSON, as_json), (INDEX_MD, as_md))
                 if not p.is_file() or p.read_text(encoding="utf-8") != want]
        for path in stale:
            print(f"{path}: out of date; run python docs/tools/build_index.py")
        return 1 if stale else 0
    INDEX_JSON.write_text(as_json, encoding="utf-8", newline="\n")
    INDEX_MD.write_text(as_md, encoding="utf-8", newline="\n")
    rows = json.loads(as_json)
    print(f"{len(rows)} files indexed, {sum(1 for r in rows if not r['metadata'])} without metadata")
    return 0


if __name__ == "__main__":
    sys.exit(main())
